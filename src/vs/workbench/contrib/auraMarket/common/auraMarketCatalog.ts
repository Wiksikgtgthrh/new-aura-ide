/**
 * when-выражение «плагин включён» — тот же ключ, что привязывает IAuraPluginService к контексту.
 * Им гейтятся вью, команды и инструменты чата плагина: отключение в маркете убирает их из
 * палитры команд и из списка инструментов модели, а не только иконку в activity bar.
 */
export function auraPluginEnabledWhenClause(itemId: string): string {
	return `auraPlugin.${itemId}.enabled == true`;
}

